# ---------------------------------------------------------------------------
# Packing (two int4 codes per byte, low nibble first).
# ---------------------------------------------------------------------------

def _pack_codes(codes: np.ndarray) -> np.ndarray:
    """uint8 codes (..., d), values 0..15 -> packed (..., d//2)."""
    c = np.asarray(codes, dtype=np.uint8)
    if c.shape[-1] % 2 != 0:
        raise ValueError("head dim %d is not even" % c.shape[-1])
    lo = c[..., 0::2].astype(np.uint8)
    hi = c[..., 1::2].astype(np.uint8)
    return (lo | (hi << 4)).astype(np.uint8)


def _unpack_codes(packed: np.ndarray) -> np.ndarray:
    """Packed (..., d//2) -> uint8 codes (..., d), low nibble first."""
    p = np.asarray(packed, dtype=np.uint8)
    out = np.empty(p.shape[:-1] + (p.shape[-1] * 2,), dtype=np.uint8)
    out[..., 0::2] = p & 0x0F
    out[..., 1::2] = (p >> 4) & 0x0F
    return out


# ---------------------------------------------------------------------------
# Quantised tensors.
# ---------------------------------------------------------------------------

class Int4Quantised:
    """int4-quantised tensor (keys or values).

    ``packed`` holds two codes per byte; ``mins`` / ``steps``
    are FP16 per group of GROUP_SIZE along the last dim;
    ``magnitudes`` is FP16 per (token, head) vector and is
    present only for the angular key arm (None otherwise) —
    the exact per-vector magnitude the angular decoder
    multiplies the renormalised direction by.
    """

    def __init__(self, shape, packed, mins, steps, magnitudes=None,
                 angular: bool = False):
        self.shape = tuple(shape)
        self.packed = np.asarray(packed, dtype=np.uint8)
        self.mins = np.asarray(mins, dtype=np.float16)
        self.steps = np.asarray(steps, dtype=np.float16)
        self.magnitudes = (
            None if magnitudes is None
            else np.asarray(magnitudes, dtype=np.float16)
        )
        self.angular = bool(angular)

    def prefix(self, n_tokens: int) -> "Int4Quantised":
        shape = (n_tokens,) + self.shape[1:]
        return Int4Quantised(
            shape,
            self.packed[:n_tokens],
            self.mins[:n_tokens],
            self.steps[:n_tokens],
            None if self.magnitudes is None else self.magnitudes[:n_tokens],
            self.angular,
        )


def _group_min_step(x: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Per-group (min, step) over the last dim, float64.

    ``x`` is (..., d) with d divisible by GROUP_SIZE; returns
    (..., nb) min and step, step = (max - min) / 15, 0 for a
    degenerate (constant) group.
    """
    d = x.shape[-1]
    if d % GROUP_SIZE != 0:
        raise ValueError(
            "head dim %d is not divisible by group size %d"
            % (d, GROUP_SIZE)
        )
    nb = d // GROUP_SIZE
    g = np.asarray(x, dtype=np.float64).reshape(x.shape[:-1] + (nb, GROUP_SIZE))
    lo = g.min(axis=-1)
    hi = g.max(axis=-1)
    step = np.where(hi > lo, (hi - lo) / 15.0, 0.0)
    return lo, step


def quantise_int4(x: np.ndarray, angular: bool = False) -> Int4Quantised:
    """Quantise (seq, heads, d) to int4, per-group asymmetric.

    With ``angular=True`` (keys only) the vector is first
    split into magnitude and unit direction and the direction
    is quantised; the magnitude is stored exactly (FP16) and
    the decoder renormalises the dequantised direction, so
    all key error is angular. With ``angular=False`` the raw
    tensor is quantised directly.
    """
    x = np.asarray(x, dtype=np.float32)
    if x.ndim != 3:
        raise ValueError("expected (seq, heads, d), got shape %s" % (x.shape,))
    seq, heads, d = x.shape
    magnitudes = None
    y = x.astype(np.float64)
    if angular:
        magnitudes = np.sqrt((y ** 2).sum(axis=-1))
        safe = np.where(magnitudes > 0, magnitudes, 1.0)
        y = y / safe[..., None]
        y = np.where((magnitudes > 0)[..., None], y, 0.0)
    mins, steps = _group_min_step(y)
    nb = d // GROUP_SIZE
    g = y.reshape(seq, heads, nb, GROUP_SIZE)
    nonzero = steps > 0
    # (seq, heads, nb, GROUP) step/min broadcast; only the
    # nonzero-step groups divide (degenerate groups stay 0).
    codes = np.where(
        nonzero[..., None],
        np.clip(
            np.round((g - mins[..., None]) / np.where(nonzero, steps, 1.0)[..., None]),
            0, 15,
        ),
        0,
    ).astype(np.uint8)
    return Int4Quantised(
        x.shape,
        _pack_codes(codes.reshape(seq, heads, d)),
        mins.astype(np.float16),
        steps.astype(np.float16),
        None if magnitudes is None else magnitudes.astype(np.float16),
        angular,
    )


def dequantise_int4(q: Int4Quantised) -> np.ndarray:
    """int4-quantised tensor -> float32 (seq, heads, d).

    Angular arm: the dequantised direction is renormalised to
    unit norm and multiplied by the stored exact magnitude —
    the same reconstruction the compressed-domain path scores
    against, so the two paths agree up to summation order.
    """
    seq, heads, d = q.shape
    nb = d // GROUP_SIZE
    codes = _unpack_codes(q.packed).reshape(seq, heads, nb, GROUP_SIZE)
    recon = (
        codes.astype(np.float64) * q.steps.astype(np.float64)[..., None]
        + q.mins.astype(np.float64)[..., None]
    )
    if q.angular:
        # Renormalise the WHOLE direction vector to unit norm
        # (not per group — per-group renormalisation would
        # distort each group's relative weight), then restore
        # the stored exact magnitude.
        flat = recon.reshape(seq, heads, d)
        norms = np.sqrt((flat ** 2).sum(axis=-1, keepdims=True))
        flat = np.where(
            norms > 0, flat / np.where(norms > 0, norms, 1.0), 0.0
        )
        flat = flat * q.magnitudes.astype(np.float64)[..., None]
        return flat.astype(np.float32)
    return recon.reshape(seq, heads, d).astype(np.float32)


# ---------------------------------------------------------------------------
# Stored-size accounting (bytes actually stored, packed codes).
# ---------------------------------------------------------------------------

def kv_stored_bytes_per_vector(d: int) -> int:
    """Stored KV bytes for one (token, head) K+V pair, head dim d.

    Codes: d/2 bytes per tensor (packed int4) = d total.
    Scales: 4 B per group (FP16 min + FP16 step) x d/32 groups
    x 2 tensors = d/4. Key magnitude: 2 B. Total 1.25d + 2.
    """
    if d % GROUP_SIZE != 0:
        raise ValueError(
            "head dim %d is not divisible by group size %d" % (d, GROUP_SIZE)
        )
    return d + d // 4 + 2


def kv_fp16_bytes_per_vector(d: int) -> int:
    """FP16 baseline bytes for one (token, head) K+V pair."""
    return 2 * d * 2


def kv_ratio(d: int) -> float:
    """Compression ratio vs the FP16 baseline (stored bytes)."""
    return kv_fp16_bytes_per_vector(d) / kv_stored_bytes_per_vector(d)


def kv_bits_per_dim(d: int) -> float:
    """Effective stored bits per dimension (K+V together)."""
    return kv_stored_bytes_per_vector(d) * 8 / (2 * d)


def kv_total_bytes(seq: int, heads: int, d: int, quantised: bool) -> int:
    """Total KV bytes for a (seq, heads, d) cache, both tensors."""
    per = (
        kv_stored_bytes_per_vector(d) if quantised
        else kv_fp16_bytes_per_vector(d)
    )
    return seq * heads * per


# ---------------------------------------------------------------------------
# Attention with an explicit scale multiplier.
# ---------------------------------------------------------------------------

def attention_with_scale(q: np.ndarray, k: np.ndarray, v: np.ndarray,
                         scale_mult: float = 1.0) -> np.ndarray:
    """Scaled dot-product attention, logits scaled by ``scale_mult``.

    Same numerics as ``kvcache.attention_float`` at
    scale_mult=1.0 (float64 scores/probs, float32 output).
    """
    q = np.asarray(q, dtype=np.float32)
    k = np.asarray(k, dtype=np.float32)
    v = np.asarray(v, dtype=np.float32)
    d = q.shape[-1]
    scale = float(scale_mult) / math.sqrt(d)
    out = np.zeros_like(q)
    for h in range(q.shape[1]):
        scores = (
            q[:, h, :].astype(np.float64) @ k[:, h, :].astype(np.float64).T
        ) * scale
        scores = scores - scores.max(axis=1, keepdims=True)
        probs = np.exp(scores)
        probs = probs / probs.sum(axis=1, keepdims=True)
        out[:, h, :] = (probs @ v[:, h, :].astype(np.float64)).astype(np.float32)
    return out


def _score_top1_mass(q: np.ndarray, k: np.ndarray,
                     scale_mult: float) -> float:
    """Mean max-softmax-probability per (query, head)."""
    d = q.shape[-1]
    scale = float(scale_mult) / math.sqrt(d)
    mass = 0.0
    total = 0
    for h in range(q.shape[1]):
        scores = (
            q[:, h, :].astype(np.float64) @ k[:, h, :].astype(np.float64).T
        ) * scale
        scores = scores - scores.max(axis=1, keepdims=True)
        probs = np.exp(scores)
        probs = probs / probs.sum(axis=1, keepdims=True)
        mass += float(probs.max(axis=1).sum())
        total += probs.shape[0]
    return mass / total if total else 1.0


def fidelity_eval(kv_orig: dict, kv_recon: dict,
                  scale_mult: float = 1.0,
                  n_queries: int = ATTN_QUERIES) -> dict:
    """Attention fidelity vs the unquantised baseline.

    Queries are the leading ``n_queries`` key rows reused as Q
    (the P7/P8 convention) and attend over ALL keys in the
    supplied KV, so a longer context really is a harder task.
    Reports attention-output error, attended-position top-1,
    vocab top-1 (fixed vocab projection, as in P8/P9) and the
    mean top-1 softmax mass of the baseline (how peaked the
    distribution the scale factor produces is).
    """
    from .kvcache import _vocab_projection

    n_q = min(n_queries, kv_orig["K"].shape[0])
    q = kv_orig["K"][:n_q]
    d = q.shape[-1]
    out_orig = attention_with_scale(q, kv_orig["K"], kv_orig["V"], scale_mult)
    out_recon = attention_with_scale(q, kv_recon["K"], kv_recon["V"], scale_mult)
    diff = out_orig.astype(np.float64) - out_recon.astype(np.float64)
    pos_agree = 0
    pos_total = 0
    for h in range(q.shape[1]):
        s_orig = (q[:, h, :].astype(np.float64)
                  @ kv_orig["K"][:, h, :].astype(np.float64).T) * scale_mult / math.sqrt(d)
        s_recon = (q[:, h, :].astype(np.float64)
                   @ kv_recon["K"][:, h, :].astype(np.float64).T) * scale_mult / math.sqrt(d)
        pos_agree += int((s_orig.argmax(axis=1) == s_recon.argmax(axis=1)).sum())
        pos_total += s_orig.shape[0]
    wv = _vocab_projection(d)
    v_orig = (out_orig.reshape(-1, d).astype(np.float64) @ wv.astype(np.float64)).argmax(axis=1)
    v_recon = (out_recon.reshape(-1, d).astype(np.float64) @ wv.astype(np.float64)).argmax(axis=1)
    return {
        "n_tokens": int(kv_orig["K"].shape[0]),
        "scale_mult": float(scale_mult),
        "max_abs_error": float(np.abs(diff).max()),
        "mse": float(np.mean(diff ** 2)),
        "attended_position_top1": pos_agree / pos_total if pos_total else 1.0,
        "vocab_top1": float(np.mean(v_orig == v_recon)),
        "top1_mass": _score_top1_mass(q, kv_orig["K"], scale_mult),
        "n_queries": int(n_q * q.shape[1]),
    }


def scale_sweep(kv_orig: dict, kv_recon_angular: dict,
                kv_recon_plain: dict,
                n_queries: int = ATTN_QUERIES) -> dict:
    """Top-1 agreement vs FP16 as a function of the scale factor.

    One sweep row per multiplier in SCALE_MULTIPLIERS, per arm.
    The attended-position column is expected to be IDENTICAL
    across multipliers (argmax commutes with positive scaling
    — see the module docstring); the vocab column is where the
    failure mode shows. Deterministic: no RNG, fixed grid.
    """
    rows = {}
    for c in SCALE_MULTIPLIERS:
        rows[str(c)] = {
            "angular": fidelity_eval(kv_orig, kv_recon_angular, c, n_queries),
            "plain": fidelity_eval(kv_orig, kv_recon_plain, c, n_queries),
        }
    return rows


# ---------------------------------------------------------------------------
# Long-context synthetic KV (same recipe as P8, parameterised).
# ---------------------------------------------------------------------------

def generate_long_kv(seq: int = LONG_SEQ, heads: int = LONG_HEADS,
                     d: int = LONG_D, seed: int = LONG_SEED,
                     latent_rank: int = LONG_LATENT_RANK,
                     noise_std: float = LONG_NOISE_STD) -> dict[str, np.ndarray]:
    """Synthetic (K, V) float32 KV at long-context shapes.

    The P8 generation recipe (latent factor draw through a
    fixed random orthonormal mix, scales decaying 1.0 -> 0.35,
    independent noise, per-channel scales clipped to
    [0.5, 1.8]) with explicit shape/seed parameters — the
    P8 profiles are fixed-shape, so the long context needs
    its own call. K and V draw independently, as in a real
    cache. Deterministic for a fixed seed.
    """
    def _one_tensor(stream_seed: int) -> np.ndarray:
        r = np.random.default_rng(stream_seed)
        mix = r.normal(size=(d, latent_rank))
        mix, _ = np.linalg.qr(mix)
        scales = np.linspace(1.0, 0.35, latent_rank)
        n_rows = seq * heads
        z = r.normal(size=(n_rows, latent_rank)) * scales[None, :]
        x = z @ mix.T
        x = x + r.normal(scale=noise_std, size=(n_rows, d))
        ch = np.clip(r.normal(1.0, 0.25, size=d), 0.5, 1.8)
        return (x * ch[None, :]).reshape(seq, heads, d).astype(np.float32)

    return {
        "K": _one_tensor(seed * 1000 + 1),
        "V": _one_tensor(seed * 1000 + 2),
    }


# ---------------------------------------------------------------------------
# Phase 3 (stretch, CPU analogue): compressed-domain attention.
# ---------------------------------------------------------------------------

def attention_compressed(q: np.ndarray, qk: Int4Quantised,
                         qv: Int4Quantised,
                         scale_mult: float = 1.0) -> np.ndarray:
    """Attention scored from the int4 codes + scales, no float KV.

    Scores are q . k_hat computed per group from the codes:
    q_g . u_hat_g = min_g * sum(q_g) + step_g * (q_g . codes_g),
    times the stored magnitude over the renormalised direction
    norm (both computed from the codes + scales alone — the
    norm needs only per-group code sums and sums of squares).
    The output is likewise accumulated from the value codes:
    sum_t p_t * v_hat_t = min_g * sum_t p_t + step_g *
    sum_t p_t * code_{t,g}, per group. The packed codes are
    unpacked to uint8 (codes, not floats) and no (seq, heads,
    d) float K or V is ever materialised — the analogue of the
    fused Metal kernel, verified against the dequantise path
    (``attention_with_scale`` on ``dequantise_int4`` output)
    to TABLE_TOL. Float64 math throughout.
    """
    if not qk.angular:
        raise ValueError("compressed-domain keys require the angular arm")
    q = np.asarray(q, dtype=np.float32)
    n_q, heads, d = q.shape
    seq_k = qk.shape[0]
    if qv.shape[0] != seq_k or qv.shape[1:] != qk.shape[1:]:
        raise ValueError("K and V shapes disagree: %s vs %s"
                         % (qk.shape, qv.shape))
    nb = d // GROUP_SIZE
    scale = float(scale_mult) / math.sqrt(d)
    out = np.zeros((n_q, heads, d), dtype=np.float32)
    codes_k = _unpack_codes(qk.packed).reshape(seq_k, heads, nb, GROUP_SIZE)
    codes_v = _unpack_codes(qv.packed).reshape(seq_k, heads, nb, GROUP_SIZE)
    for h in range(heads):
        qh = q[:, h, :].astype(np.float64).reshape(n_q, nb, GROUP_SIZE)
        ck = codes_k[:, h].astype(np.float64)  # (seq, nb, G)
        mins_k = qk.mins[:, h].astype(np.float64)  # (seq, nb)
        steps_k = qk.steps[:, h].astype(np.float64)
        # Per-group code dot: (nq, seq, nb).
        dots = np.einsum("qbg,sbg->qsb", qh, ck)
        qsum = qh.sum(axis=2)  # (nq, nb)
        group_scores = dots * steps_k[None, :, :] + mins_k[None, :, :] * qsum[:, None, :]
        # ||u_hat||^2 per key, from per-group code sums alone:
        # sum_i (min + c*step)^2 = G*min^2 + 2*min*step*sum(c)
        # + step^2*sum(c^2).
        sum_c = ck.sum(axis=2)  # (seq, nb)
        sum_c2 = (ck ** 2).sum(axis=2)
        norm_sq = (
            GROUP_SIZE * mins_k ** 2
            + 2.0 * mins_k * steps_k * sum_c
            + steps_k ** 2 * sum_c2
        ).sum(axis=1)  # (seq,)
        mags = qk.magnitudes[:, h].astype(np.float64)
        norm_factor = np.where(
            norm_sq > 0, mags / np.sqrt(np.where(norm_sq > 0, norm_sq, 1.0)), 0.0
        )
        scores = group_scores.sum(axis=2) * norm_factor[None, :] * scale
        scores = scores - scores.max(axis=1, keepdims=True)
        probs = np.exp(scores)
        probs = probs / probs.sum(axis=1, keepdims=True)
        # Values from codes: (nq, nb, G).
        cv = codes_v[:, h].astype(np.float64)  # (seq, nb, G)
        mins_v = qv.mins[:, h].astype(np.float64)
        steps_v = qv.steps[:, h].astype(np.float64)
        min_term = (probs @ mins_v)[:, :, None]  # (nq, nb, 1)
        weighted = probs[:, :, None] * steps_v[None, :, :]  # (nq, seq, nb)
        step_term = np.einsum("qsb,sbg->qbg", weighted, cv)
        out[:, h, :] = (min_term + step_term).reshape(n_q, d).astype(np.float32)
    return out


