"""P15 — int4 KV quantisation + correctness harness (Apple Silicon slice).

Open-TQ-Metal (arXiv:2604.16957): the realistic slice of fused
compressed-domain attention — int4 KV quantisation with a
correctness harness (top-1 agreement vs FP16) on MLX; the fused
Metal kernel is stretch.

SUBSTITUTIONS, stated plainly (this VM is Linux x86 — there is
no Mac, no MLX, no 70B model and no 128K real context here, so
do NOT read this module as a run on MLX, on a Mac, or on a real
model):
- No MLX. Everything is pure NumPy on SYNTHETIC KV: the same
  two fixed P8 profiles (shapes, seeds, cross-channel-correlated
  generation, reused via ``kvcache.generate_synthetic_kv``),
  plus one long synthetic context (16,384 tokens, 8 heads,
  d=64) generated by the same recipe, parameterised — the
  analogue of the plan's 128K test, sized to fit this VM's
  memory. The 128K / 70B numbers appear only as an arithmetic
  projection from the measured ratio, labelled as such.
- No perplexity. The metric is ATTENTION FIDELITY vs the
  unquantised baseline on P8's deterministic attention task:
  attended-position top-1, vocab top-1 through the fixed
  vocab projection, and attention-output error.
- No Metal kernel. Phase 3 is a NumPy compressed-domain
  attention path (scores from the int4 codes + scales, no
  float KV materialised) — the same idea as P9's table trick
  — verified against the dequantise-then-attend path, not
  benchmarked as a kernel.

SCHEME (frozen before measuring — nothing below was tuned
after the numbers came out):
- int4, asymmetric, per-group: GROUP_SIZE = 32 consecutive
  dims share one FP16 min and one FP16 step, step =
  (max - min) / 15, codes 0..15 packed two per byte (low
  nibble first). A degenerate group (max == min) stores
  step 0 and reconstructs exactly. Per-element error is
  <= step/2 plus FP16 rounding of the stored min/step.
- Keys, ANGULAR arm (the paper's angular idea, one concrete
  construction): each key vector is split into magnitude
  m = ||k|| (one FP16 per vector) and unit direction
  u = k / m; the direction is int4-quantised per group as
  above, and the decoder renormalises the dequantised
  direction back to unit norm, so k_hat = m * u_hat/||u_hat||
  — the magnitude is exact and ALL key error is angular.
  A zero key (m = 0) quantises to all-zero codes and
  reconstructs to exactly zero.
- Keys, PLAIN arm (control): the same per-group int4 on the
  raw key — magnitude and direction error together. The two
  arms share the value quantiser, the scale grid and the
  data, so any difference is the angular construction.
- Values: per-group int4 asymmetric in both arms (values
  never enter the softmax, so no angular split).
- Stored size per (token, head) K+V pair: d codes bytes
  (d/2 per tensor, packed) + d/4 scale bytes (4 B per group
  x d/32 groups x 2 tensors) + 2 B key magnitude = 1.25d + 2
  bytes vs 4d bytes for the FP16 baseline (2 B/elem x 2
  tensors) — 3.16x at d=128, 3.12x at d=64. The plan's
  40 GB -> ~12.5 GB is 3.2x; the measured ratio is reported
  per profile, not asserted.

KEY DECISION — the attention scale factor (tested explicitly):
the sweep multiplies the standard 1/sqrt(d) scale by
c in SCALE_MULTIPLIERS = (0.25, 0.5, 1, 2, 4, 8), applied
identically to the baseline and the quantised arms. Two
things the sweep establishes, one of them by proof:
- Attended-position top-1 is EXACTLY invariant to c:
  argmax commutes with multiplication by a positive
  constant, and the quantisation happens once, before any
  scaling — so scaling the logits of both arms by the same
  c cannot flip which position either arm attends to most
  (up to float rounding). The sweep pins this: the
  attended column is identical for every c. The failure
  mode therefore cannot show up in attended top-1, and any
  harness that only reports attended top-1 would call the
  quantiser scale-proof when it is not.
- The failure mode shows up where c actually bites: the
  SOFTMAX. Vocab top-1 (through the attention output) and
  output error move with c, because a sharper softmax turns
  the same angular error into larger probability swings and
  concentrates the output on fewer (quantised) values. The
  sweep reports vocab top-1, output MSE and mean top-1
  probability mass per c, per arm — the c at which vocab
  top-1 falls is the break point, and the angular arm's
  break point vs the plain arm's is the measurement of
  whether the angular construction buys scale robustness.
"""

